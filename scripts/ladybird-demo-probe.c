/* Fetch-Probe fuer scripts/ladybird-demo-run.sh --selftest: schreibt ein gueltiges 1x1-PNG nach /shot.png (Prozesswurzel =
 * Platten-Ordner lb) und endet mit 0. Prueft so den Weg Gast -> Platten-Kopie -> fetch-data-disk-file.py ohne Ladybird.
 * Bauen: gcc -static -O1 -o probe scripts/ladybird-demo-probe.c (nur Systemaufrufe open/write/close). */
#include <fcntl.h>
#include <unistd.h>

static const unsigned char png[] = {
    0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, 0x00, 0x00, 0x00, 0x0d, 0x49, 0x48, 0x44, 0x52, 0x00, 0x00, 0x00, 0x01,
    0x00, 0x00, 0x00, 0x01, 0x08, 0x02, 0x00, 0x00, 0x00, 0x90, 0x77, 0x53, 0xde, 0x00, 0x00, 0x00, 0x0c, 0x49, 0x44, 0x41,
    0x54, 0x08, 0xd7, 0x63, 0xf8, 0xcf, 0xc0, 0x00, 0x00, 0x03, 0x01, 0x01, 0x00, 0x18, 0xdd, 0x8d, 0xb0, 0x00, 0x00, 0x00,
    0x00, 0x49, 0x45, 0x4e, 0x44, 0xae, 0x42, 0x60, 0x82};

int main(void) {
    int fd = open("/shot.png", O_WRONLY | O_CREAT | O_TRUNC, 0644);
    if (fd < 0) return 2;
    if (write(fd, png, sizeof png) != (ssize_t)sizeof png) return 3;
    return close(fd) == 0 ? 0 : 4;
}
